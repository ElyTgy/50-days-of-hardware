#!/usr/bin/env node
// Generates public/llm/*.md from the live Supabase data — the same tables
// the site itself reads (see src/lib/days.tsx, src/data/blocks.ts,
// src/types.ts). Run via `npm run build` (wired in as a `prebuild` step) or
// directly: `node scripts/generate-llm-files.mjs`.
//
// These files exist so a client-rendered SPA isn't an empty shell to an LLM
// fetching it by URL — see public/llm/index.md once generated.

import { createClient } from "@supabase/supabase-js";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "public", "llm");
const HEADER =
  "<!-- Generated by scripts/generate-llm-files.mjs — do not edit by hand. -->\n\n";

// ---- mirrors src/data/blocks.ts (kept in sync by hand; changes rarely) ----
const BLOCKS = [
  { id: 0, name: "Capacitive touch" },
  { id: 1, name: "Passives & filters" },
  { id: 2, name: "Devices" },
  { id: 3, name: "Op-amps & PLLs" },
  { id: 4, name: "Power electronics" },
  { id: 5, name: "RF" },
  { id: 6, name: "Digital design" },
  { id: 7, name: "Firmware" },
];
const blockName = (id) => BLOCKS.find((b) => b.id === id)?.name ?? `Block ${id}`;

const CHALLENGE_START = new Date(2026, 7, 5); // Wed Aug 5, 2026
const dateForDay = (n) => {
  const d = new Date(CHALLENGE_START);
  d.setDate(d.getDate() + (n - 1));
  return d;
};
const formatDateLong = (d) =>
  d.toLocaleDateString("en-US", {
    weekday: "long",
    month: "long",
    day: "numeric",
    year: "numeric",
  });

// ---- mirrors src/types.ts DAY_SECTIONS ----
const DAY_SECTIONS = [
  ["equipment", "Equipment needed"],
  ["prerequisites", "Prerequisites"],
  ["intro", "Introduction & background"],
  ["equations", "Core equations"],
  ["diagram", "Diagram"],
  ["assembled", "What you're building"],
  ["activity", "Activity"],
  ["question", "Question to answer"],
  ["resources", "Additional resources"],
];

// ---- env / client ----------------------------------------------------
function loadLocalEnv() {
  // Vercel/CI inject env vars directly into process.env — this is only for
  // running the script locally, and it's fine if the file doesn't exist.
  try {
    process.loadEnvFile(path.join(ROOT, ".env.local"));
  } catch {
    /* no .env.local — fine */
  }
}
loadLocalEnv();

const SUPABASE_URL = process.env.VITE_SUPABASE_URL;
const SUPABASE_KEY =
  process.env.VITE_SUPABASE_ANON_KEY ?? process.env.VITE_SUPABASE_PUBLISHABLE_KEY;

if (!SUPABASE_URL || !SUPABASE_KEY) {
  console.warn(
    "[generate-llm-files] VITE_SUPABASE_URL/ANON_KEY not set — skipping LLM file generation (build continues).",
  );
  process.exit(0);
}

const supabase = createClient(SUPABASE_URL, SUPABASE_KEY);

// ---- helpers -----------------------------------------------------------
const pad2 = (n) => String(n).padStart(2, "0");
const clean = (s) => (s ?? "").toString().trim();
const NOT_WRITTEN = "_Not written yet._";

const sectionBlock = (title, body) =>
  `## ${title}\n\n${clean(body) || NOT_WRITTEN}\n`;

/** First non-empty line of activity (falling back to intro), trimmed. */
function oneLiner(day) {
  const src = clean(day.activity) || clean(day.intro);
  if (!src) return NOT_WRITTEN;
  const line = src.split(/\n+/)[0].replace(/\s+/g, " ").trim();
  return line.length > 140 ? line.slice(0, 137).trimEnd() + "…" : line;
}

/** Markdown table cells can't contain a raw `|` or newline. */
const cell = (s) => clean(s).replace(/\|/g, "\\|").replace(/\s+/g, " ");

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  const { data: dayRows, error: dayErr } = await supabase.from("days").select("*");
  if (dayErr) throw dayErr;
  const { data: itemRows, error: itemErr } = await supabase
    .from("shopping_items")
    .select("*");
  if (itemErr) throw itemErr;

  const scheduled = (dayRows ?? [])
    .filter((d) => d.position !== null)
    .sort((a, b) => Number(a.position) - Number(b.position))
    .map((d, i) => ({ ...d, number: i + 1 }));

  // ---- index.md --------------------------------------------------------
  let index = HEADER;
  index += "# 40 Days of Hardware — day index\n\n";
  index += `${scheduled.length} scheduled days. Full content for each is at \`day-NN.md\` in this folder ` +
    `(e.g. \`day-01.md\`). This file is a table of contents only.\n\n`;
  index += "| Day | Date | Title | Block | Summary |\n";
  index += "| --- | --- | --- | --- | --- |\n";
  for (const d of scheduled) {
    index +=
      `| ${d.number} | ${cell(formatDateLong(dateForDay(d.number)))} | ` +
      `${cell(d.topic) || "Untitled"} | ${cell(blockName(d.block_id))} | ${cell(oneLiner(d))} |\n`;
  }
  await writeFile(path.join(OUT_DIR, "index.md"), index);

  // ---- day-NN.md ---------------------------------------------------------
  for (const d of scheduled) {
    let md = HEADER;
    md += `# Day ${d.number}: ${clean(d.topic) || "Untitled"}\n\n`;
    md += `- Date: ${formatDateLong(dateForDay(d.number))}\n`;
    md += `- Block: ${blockName(d.block_id)}\n`;
    if (d.puzzle) md += `- Puzzle day: yes\n`;
    md += "\n";
    for (const [field, title] of DAY_SECTIONS) {
      md += sectionBlock(title, d[field]) + "\n";
    }
    await writeFile(path.join(OUT_DIR, `day-${pad2(d.number)}.md`), md);
  }

  // ---- inventory.md ------------------------------------------------------
  const items = itemRows ?? [];
  const itemLine = (i) => {
    const qty = i.min_quantity && i.min_quantity > 1 ? ` (min qty: ${i.min_quantity})` : "";
    const days = clean(i.days_required_for)
      ? ` — needed for day(s) ${clean(i.days_required_for)}`
      : "";
    const link = clean(i.link) ? ` — [link](${clean(i.link)})` : "";
    const what = clean(i.what_it_does);
    return (
      `- **${clean(i.part_name) || "Untitled part"}**${qty}${days}${link}` +
      (what ? `\n  ${what}` : "")
    );
  };
  const group = (title, rows) =>
    `## ${title}\n\n` +
    (rows.length ? rows.map(itemLine).join("\n") + "\n" : "_None._\n") +
    "\n";

  let inv = HEADER;
  inv += "# Inventory\n\n";
  inv += group(
    "Owned",
    items.filter((i) => i.status === "owned").sort((a, b) => a.part_name.localeCompare(b.part_name)),
  );
  inv += group(
    "Incoming (ordered, not yet received)",
    items.filter((i) => i.status === "ordered").sort((a, b) => a.part_name.localeCompare(b.part_name)),
  );
  inv += group(
    "Not yet ordered",
    items
      .filter((i) => i.status === "not ordered")
      .sort((a, b) => a.part_name.localeCompare(b.part_name)),
  );
  await writeFile(path.join(OUT_DIR, "inventory.md"), inv);

  // ---- questions.md --------------------------------------------------------
  let q = HEADER;
  q += "# Check-yourself question references\n\n";
  q +=
    "Question NUMBERS and source names only. Do not add verbatim third-party " +
    "question text here (Monty Choy's list, hardware-interview.com, Fronczak's " +
    "questions, etc.) — reference by name and number, the way the source data " +
    "already does.\n\n";
  for (const block of BLOCKS) {
    const days = scheduled.filter((d) => d.block_id === block.id && clean(d.resources));
    if (!days.length) continue;
    q += `## ${block.name}\n\n`;
    for (const d of days) {
      q += `### Day ${d.number} — ${clean(d.topic) || "Untitled"}\n\n`;
      q += `${clean(d.resources)}\n\n`;
    }
  }
  await writeFile(path.join(OUT_DIR, "questions.md"), q);

  console.log(
    `[generate-llm-files] wrote index.md, day-01..${pad2(scheduled.length)}.md, inventory.md, questions.md to public/llm/`,
  );
}

main().catch((err) => {
  console.error("[generate-llm-files] failed:", err);
  process.exit(1);
});
